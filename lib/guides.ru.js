export function getGuideRu(slug) {
  return GUIDES_RU.find((g) => g.slug === slug) || null;
}

// --- Price drift guard -------------------------------------------------------
// Collects every number in a guide's body text (intro, sections, FAQs) and
// compares it with the English source. Thousands separators (comma in English,
// space in Russian) are ignored. Throws at build time on any mismatch.
function numbersIn(guide) {
  const text = JSON.stringify([guide.intro, guide.sections, guide.faqs]);
  const found = text.match(/\d{1,3}(?:[,  ]\d{3})+|\d+/g) || [];
  return [...new Set(found.map((n) => n.replace(/[,  ]/g, "")))].sort();
}

function checkNumbersMatch() {
  for (const slug of RU_GUIDE_SLUGS) {
    const en = GUIDES.find((g) => g.slug === slug);
    const ru = GUIDES_RU.find((g) => g.slug === slug);
    if (!en || !ru) throw new Error(`guides.ru.js: missing English or Russian guide "${slug}"`);
    const a = numbersIn(en).join(" ");
    const b = numbersIn(ru).join(" ");
    if (a !== b) {
      throw new Error(`guides.ru.js: numbers in "${slug}" differ from the English guide.\n  en: ${a}\n  ru: ${b}`);
    }
  }
}

